"""Composed polynomial coordinates for a generic small gated operator.

Run from any directory with the project scientific Python and BLAS_NUM_THREADS=1.
The JSON receipt is written to stdout. No model weights are generated by fitting
an output polynomial; its coefficients are expanded from the full operator.
"""
import itertools
import json
import time

import numpy as np

N, H, M = 3, 32, 4


def exponents(degrees):
    return [e for degree in degrees for e in itertools.product(range(degree + 1), repeat=N) if sum(e) == degree]


def expand(weights, degrees):
    gate, up, down = weights
    powers = exponents(degrees)
    columns = {p: i for i, p in enumerate(powers)}
    result = np.zeros((M, len(columns)))
    # SiLU(t) = t/2 + t**2/4 - t**4/48 + ... . The quadratic
    # operator is exactly the first term, while the other terms
    # are an approximation to SiLU only on a bounded gate domain.
    for degree, factor in [(1, .5), (2, .25), (4, -1 / 48)]:
        if degree + 1 not in degrees:
            continue
        for indices in itertools.product(range(N), repeat=degree):
            eg = tuple(indices.count(k) for k in range(N))
            g = np.prod(gate[:, indices], axis=1) * factor
            for j in range(N):
                p = tuple(eg[k] + (k == j) for k in range(N))
                result[:, columns[p]] += down @ (g * up[:, j])
    return result, powers


def features(x, powers):
    return np.stack([np.prod(x ** np.asarray(p), axis=1) for p in powers], axis=1)


def fit_codes(weights, maximum, per_row):
    # Fixed code alphabet. Scales are conversion-time constants stored as FP16.
    # Least-squares scale is refitted after rounding codes; output codes and
    # scales, rather than float coefficients, are what the reader consumes.
    out = np.zeros_like(weights)
    scales = []
    groups = list(weights) if per_row else [weights.reshape(-1)]
    for group in groups:
        group = np.asarray(group)
        bound = float(np.max(np.abs(group)))
        scale = max(bound / maximum, 1e-12)
        for _ in range(12):
            code = np.clip(np.rint(group / scale), -maximum, maximum)
            denom = float(np.dot(code, code))
            if denom:
                scale = max(float(np.dot(group, code)) / denom, 1e-12)
        scales.append(float(np.float16(scale)))
    if per_row:
        for i, row in enumerate(weights):
            out[i] = np.clip(np.rint(row / scales[i]), -maximum, maximum) * scales[i]
    else:
        out[:] = np.clip(np.rint(weights / scales[0]), -maximum, maximum) * scales[0]
    return out, scales


def quant_weights(weights, maximum, per_row):
    copies = []
    count = 0
    for w in weights:
        q, s = fit_codes(w, maximum, per_row)
        copies.append(q)
        count += len(s)
    if maximum == 1:
        # An independently addressed row is a radix-3 integer in ceil(log2(3**K)/8)
        # bytes. Matrix-wise blocks are smaller but still row-addressable only
        # after parsing the whole matrix, so both arms use the same row layout.
        payload = sum(w.shape[0] * (((3 ** w.shape[1]).bit_length() + 7) // 8) for w in weights)
    else:
        # Adjacent signed four-bit row codes share a byte where a row ends at
        # a half-byte offset. The fixed row width locates any row without padding.
        payload = (sum(w.size for w in weights) + 1) // 2
    return copies, payload + 2 * count


def direct(coeff, maximum):
    q, scales = fit_codes(coeff, maximum, True)
    payload = coeff.size if maximum == 127 else sum((len(row) + 1) // 2 for row in coeff)
    return q, payload + 2 * len(scales)


def teacher(weights, x, kind):
    gate, up, down = weights
    g = x @ gate.T
    u = x @ up.T
    if kind == 'glu':
        z = g * u * .5
    else:
        z = (g / (1 + np.exp(-g))) * u
    return z @ down.T


def rmse(a, b):
    return float(np.linalg.norm(a - b) / np.linalg.norm(b))


def timed(function, x, repeat=80):
    function(x)
    samples = []
    for _ in range(5):
        start = time.perf_counter()
        for _ in range(repeat):
            function(x)
        samples.append((time.perf_counter() - start) * 1e6 / repeat)
    return float(np.median(samples))


def run(seed):
    rng = np.random.default_rng(seed)
    weights = (rng.normal(0, .7, (H, N)), rng.normal(0, .65, (H, N)), rng.normal(0, 1 / np.sqrt(H), (M, H)))
    panels = {'train': rng.normal(0, .6, (512, N)), 'held': rng.normal(0, .8, (1024, N)), 'wide': rng.normal(0, 2.3, (1024, N))}
    bases = {name: expand(weights, deg) for name, deg in [('quadratic', (2,)), ('cubic', (2, 3)), ('quintic', (2, 3, 5))]}
    scalar = {name: quant_weights(weights, maximum, row) for name, maximum, row in [('ternary_tensor', 1, False), ('ternary_row', 1, True), ('q4_tensor', 7, False)]}
    images = {name: (q, bytes_, None) for name, (q, bytes_) in scalar.items()}
    for name, (coeff, powers) in bases.items():
        for label, maximum in [('int8', 127), ('q4', 7)]:
            q, bytes_ = direct(coeff, maximum)
            images[name + '_' + label] = (q, bytes_, powers)
        images[name + '_fp16'] = (coeff.astype(np.float16).astype(np.float64), coeff.size * 2, powers)
    result = {'seed': seed, 'images': {}, 'quadratic_roundtrip': {}, 'gate_abs_max': {}}
    for panel, x in panels.items():
        gt = teacher(weights, x, 'glu')
        st = teacher(weights, x, 'silu')
        result['gate_abs_max'][panel] = float(np.max(np.abs(x @ weights[0].T)))
        plain, powers = bases['quadratic']
        result['quadratic_roundtrip'][panel] = rmse(features(x, powers) @ plain.T, gt)
        for name, (image, bytes_, powers) in images.items():
            if powers is None:
                pred_glu = teacher(image, x, 'glu')
                pred_silu = teacher(image, x, 'silu')
            else:
                pred_glu = features(x, powers) @ image.T if name.startswith('quadratic') else None
                pred_silu = features(x, powers) @ image.T
            item = result['images'].setdefault(name, {'bytes': bytes_, 'terms': len(powers) if powers else H, 'errors': {}})
            errs = {'silu': rmse(pred_silu, st)}
            if pred_glu is not None:
                errs['glu'] = rmse(pred_glu, gt)
            item['errors'][panel] = errs
    if seed == 101:
        x = panels['held'][:256]
        result['microseconds_per_256_batch'] = {}
        for name in ['ternary_tensor', 'q4_tensor', 'quadratic_int8', 'cubic_int8', 'quintic_int8']:
            image, _, powers = images[name]
            result['microseconds_per_256_batch'][name] = timed(lambda batch: teacher(image, batch, 'silu') if powers is None else features(batch, powers) @ image.T, x)
    return result


if __name__ == '__main__':
    seeds = [101, 102, 103, 104, 105, 106, 107, 108]
    results = [run(seed) for seed in seeds]
    names = results[0]['images'].keys()
    summary = {}
    for name in names:
        summary[name] = {'bytes': results[0]['images'][name]['bytes'], 'terms': results[0]['images'][name]['terms']}
        for panel in ('held', 'wide'):
            for kind in ('silu', 'glu'):
                values = [r['images'][name]['errors'][panel].get(kind) for r in results]
                if all(v is not None for v in values):
                    summary[name][panel + '_' + kind] = {'median': float(np.median(values)), 'min': float(np.min(values)), 'max': float(np.max(values))}
    print(json.dumps({'shape': {'input': N, 'hidden': H, 'output': M}, 'seeds': seeds, 'summary': summary, 'runs': results}, indent=2))
